import assert from "node:assert/strict";
import fs from "node:fs";
import { resolveGranularConsentOptions } from "../src/lib/legal.ts";

const opts = resolveGranularConsentOptions([
  { consent_type: "health_data", granted: false, created_at: "2026-10-15T10:00:00Z" },
  { consent_type: "health_data", granted: true, created_at: "2026-10-14T10:00:00Z" },
  { consent_type: "health_cloud_sync", granted: true, created_at: "2026-10-15T09:00:00Z" },
  { consent_type: "unknown_category", granted: true, created_at: "2026-10-15T11:00:00Z", decision_sequence: 99 },
  { consent_type: "health_data", granted: true, created_at: "2026-10-15T10:00:00Z", decision_sequence: 20 },
  { consent_type: "health_data", granted: false, created_at: "2026-10-15T10:00:00Z", decision_sequence: 21 },
]);

assert.equal(opts.health_data, false, "a prior grant must not override a newer revocation");
assert.equal(opts.health_cloud_sync, true, "the newest grant should be honored");
assert.equal(opts.financial_data, false, "missing categories must fail closed");
assert.equal(opts.marketing, false, "unknown categories must not enable consent");

const atomicConsentMigration = fs.readFileSync("supabase/migrations/20261015111500_atomic_legal_consent.sql", "utf8");
const legalFunctions = fs.readFileSync("src/lib/legal.functions.ts", "utf8");
assert.match(atomicConsentMigration, /save_legal_consent_atomic/);
assert.match(atomicConsentMigration, /auth\.uid\(\) <> p_user_id/);
assert.match(atomicConsentMigration, /insert into public\.consent_records/);
assert.match(legalFunctions, /rpc\(\s*"save_legal_consent_atomic"/);
assert.match(legalFunctions, /\.eq\("legal_version", LEGAL_VERSIONS\.eula\)/);
assert.match(legalFunctions, /\.eq\("policy_version", LEGAL_VERSIONS\.privacy\)/);
assert.doesNotMatch(legalFunctions, /from\("consent_records"\)\.insert\(records\)/);

const consentMigration = fs.readFileSync("supabase/migrations/20261015110000_consent_decision_sequence.sql", "utf8");
assert.match(consentMigration, /decision_sequence bigint generated by default as identity/i);
assert.match(consentMigration, /created_at desc, decision_sequence desc/i);

assert.doesNotMatch(legalFunctions, /\["analytics", "notifications", "sync_cloud", "ai", "marketing"\]/);
const aiConsentSource = fs.readFileSync("src/lib/ai-consent.server.ts", "utf8");
