-- Provide a monotonic database-assigned tie-breaker for consent decisions.
-- created_at remains the primary ordering key; this sequence resolves rows that
-- share a timestamp without relying on random UUID ordering.
alter table public.consent_records
  add column if not exists decision_sequence bigint generated by default as identity;

create index if not exists consent_records_user_type_decision_idx
  on public.consent_records (user_id, consent_type, created_at desc, decision_sequence desc);
